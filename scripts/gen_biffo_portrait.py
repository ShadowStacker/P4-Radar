#!/usr/bin/env python3
"""Packs assets/biffo/biffo_portrait.png (Squadron Leader Biffo, for the boot
screen) into main/data/biffo_portrait_data.cpp as a small palette PNG.

    python3 scripts/gen_biffo_portrait.py
"""
import io
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'biffo', 'biffo_portrait.png')
OUT = os.path.join(ROOT, 'main', 'data', 'biffo_portrait_data.cpp')

im = Image.open(SRC).convert('RGBA')
# 8-bit palette with per-entry alpha (tRNS): a fraction of the RGBA size,
# and core::png decodes it.
pal = im.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.FLOYDSTEINBERG)
buf = io.BytesIO()
pal.save(buf, format='PNG', optimize=True)
data = buf.getvalue()

lines = []
for i in range(0, len(data), 20):
    lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 20]) + ',')
with open(OUT, 'w') as f:
    f.write('// Generated by scripts/gen_biffo_portrait.py from assets/biffo/biffo_portrait.png - do not edit.\n')
    f.write('#include "data/biffo_portrait.h"\n\nnamespace data {\n\n')
    f.write(f'const uint8_t kBiffoPortraitPng[{len(data)}] = {{\n' + '\n'.join(lines) + '\n};\n')
    f.write(f'const uint32_t kBiffoPortraitPngLen = {len(data)};\n\n}}  // namespace data\n')
print(f'{OUT}: {im.width}x{im.height}, {len(data)} bytes')
