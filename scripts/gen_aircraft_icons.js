#!/usr/bin/env node
// Renders the aircraft SVG icons (assets/aircraft_icons, by ADS-B Radar -
// https://adsb-radar.com, and assets/aircraft_icons/generated, drawn in their
// style by scripts/aircraft_families.py) into compressed alpha masks:
//   main/data/aircraft_icons_data.cpp
//
// Needs Node and Playwright with Chromium (the SVGs are drawn by the browser).
//   node scripts/gen_aircraft_icons.js
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'assets', 'aircraft_icons');
const OUT = path.join(ROOT, 'main', 'data', 'aircraft_icons_data.cpp');
const SIZE = 128;      // mask edge, px
const FILL = 0.92;     // the shape's share of the mask: room for wingtips when rotated

(async () => {
  // The ADS-B Radar icons, plus the ones scripts/aircraft_families.py draws in their style.
  const GEN = path.join(SRC, 'generated');
  const files = [
    ...fs.readdirSync(SRC).filter((f) => f.endsWith('.svg')).map((f) => path.join(SRC, f)),
    ...(fs.existsSync(GEN) ? fs.readdirSync(GEN).filter((f) => f.endsWith('.svg')).map((f) => path.join(GEN, f)) : []),
  ].sort((a, b) => path.basename(a).localeCompare(path.basename(b)));
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const masks = [];
  for (const f of files) {
    const svg = fs.readFileSync(f, 'utf8');
    const alpha = await page.evaluate(async ({ svg, size, fill }) => {
      const img = new Image();
      img.src = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(svg)));
      await img.decode();
      const c = document.createElement('canvas');
      c.width = c.height = size;
      const ctx = c.getContext('2d');
      const s = size * fill;
      ctx.drawImage(img, (size - s) / 2, (size - s) / 2, s, s);
      const d = ctx.getImageData(0, 0, size, size).data;
      const a = new Array(size * size);
      for (let i = 0; i < size * size; ++i) a[i] = d[i * 4 + 3];
      return a;
    }, { svg, size: SIZE, fill: FILL });
    const packed = zlib.deflateRawSync(Buffer.from(alpha), { level: 9 });
    masks.push({ name: path.basename(f, '.svg'), packed });
  }
  await browser.close();

  let out = '// Generated by scripts/gen_aircraft_icons.js - do not edit.\n';
  out += '// Icons by ADS-B Radar for macOS - https://adsb-radar.com - https://apps.apple.com/app/id1538149835\n';
  out += '// (free for personal and commercial use with a backlink; see assets/aircraft_icons/README.md)\n\n';
  out += '#include "data/aircraft_icons.h"\n\nnamespace data {\n\nnamespace {\n\n';
  for (const m of masks) {
    out += `const uint8_t k_${m.name}[] = {`;
    for (let i = 0; i < m.packed.length; ++i) {
      if (i % 20 === 0) out += '\n   ';
      out += ` ${m.packed[i]},`;
    }
    out += '\n};\n\n';
  }
  out += '}  // namespace\n\n';
  out += `const IconMask kIconMasks[] = {\n`;
  for (const m of masks) out += `    {"${m.name}", ${SIZE}, k_${m.name}, sizeof(k_${m.name})},\n`;
  out += '};\n';
  out += 'const int kIconMaskCount = static_cast<int>(sizeof(kIconMasks) / sizeof(kIconMasks[0]));\n\n';
  out += '}  // namespace data\n';
  fs.writeFileSync(OUT, out);
  const total = masks.reduce((n, m) => n + m.packed.length, 0);
  console.log(`${masks.length} icons, ${total} bytes compressed -> ${path.relative(ROOT, OUT)}`);
})();
